import assert from 'node:assert/strict';import {readFileSync} from 'node:fs';import vm from 'node:vm';
const html=readFileSync(new URL('../server/src/admin/index.html',import.meta.url),'utf8');
const ctx=vm.createContext({structuredClone,esc:x=>String(x),window:{__models:[]}});
vm.runInContext(html.slice(html.indexOf('const IMAGE_SIZE_DRAFTS='),html.indexOf('function materialPolicyValue(')),ctx);
const m={id:'seedream',capability:'image',params:[{key:'resolution',type:'enum',options:['1k','1.5k','2k']},{key:'size',type:'enum',options:['1:1','3:2','2:3']}],imageSizeMap:{'3:2':{'1.5k':'1872x1248'},'2:3':{'2k':'1664x2496'}}};
const axes=model=>JSON.parse(JSON.stringify(ctx.imageSizeAxes(model)));
assert.deepEqual(axes(m),{resolutions:['1k','1.5k','2k'],aspects:['1:1','3:2','2:3']});
const view=ctx.imageSizeFields(m);assert.ok(view.includes('<th>1.5K</th>')&&!view.includes('<th>4K</th>'));assert.ok(view.includes('1872x1248'));
const changed=structuredClone(m);changed.params[1].inImageSizeMap=false;assert.equal(axes(changed).aspects.length,0);
changed.params[1].inImageSizeMap=true;changed.params[0].options.push('4k');assert.equal(axes(changed).resolutions.length,4);
ctx.imageSizeDraft(m).map['3:2']['1.5k']='1920x1280';ctx.imageSizeFields(changed);assert.equal(ctx.imageSizeDraft(m).map['3:2']['1.5k'],'1920x1280');
const fresh={...m,id:'new',imageSizeMap:undefined};assert.equal(axes(fresh).aspects.length,0);fresh.params=structuredClone(m.params).map(p=>({...p,inImageSizeMap:true}));assert.equal(axes(fresh).aspects.length,3);
const legacy={...m,id:'legacy',params:[m.params[0],{key:'size',type:'enum',options:['1872x1248']}]};assert.deepEqual(axes(legacy).aspects,['3:2','2:3']);
const target={'3:2':{'1.5k':'2000x1400'},'2:3':{'4k':'3000x4500'}};
const source=structuredClone(m.imageSizeMap);
assert.equal(ctx.fillImageSizePreset(target,source,axes(m)),1);
assert.equal(target['3:2']['1.5k'],'2000x1400');
assert.equal(target['2:3']['2k'],'1664x2496');
assert.equal(ctx.fillImageSizePreset(target,source,axes(m),true),2);
assert.equal(target['3:2']['1.5k'],'1872x1248');
assert.equal(target['2:3']['4k'],'3000x4500');
assert.deepEqual(source,m.imageSizeMap);
ctx.window.__models=[m,{id:'empty',capability:'image'}, {...m,id:'video',capability:'video'}];
assert.equal(ctx.imageSizePresets().length,1);
assert.ok(ctx.imageSizeFields(m).includes('填入空白'));
console.log('IMAGE_SIZE_EDITOR 18 checks passed');
