import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
if (!import.meta.url.includes('qiji-token-billing-')) throw new Error('Sandbox only');
globalThis.fetch=async()=>{throw new Error('Restart test must never call upstream');};
const proof=JSON.parse(readFileSync('./text-billing-proof.json','utf8'));
const {userCredits}=await import('../src/store/users.ts');
const {selfHealCredits}=await import('../src/store/credits.ts');
const {recoverTextBillingResults}=await import('../src/store/textBilling.ts');
const {ledgerSettleTerminal}=await import('../src/relay.ts');
const {flushPendingSaves}=await import('../src/store/db.ts');
const {closeSqlite}=await import('../src/store/sqlite.ts');
const {getModelDef}=await import('../src/store/models.ts');
assert.deepEqual(getModelDef('token-smoke').tokenPricing.peak.schedule,{days:[6],periods:[{start:'22:30',end:'02:15'}]});
selfHealCredits();
recoverTextBillingResults();
recoverTextBillingResults();
ledgerSettleTerminal('mirror-test','success',{response:{billing:{status:'settled',cost:80}}});
assert.equal(userCredits(proof.userId),proof.lastBalance);
assert.equal(userCredits(proof.mirrorUserId),proof.mirrorBalance);
await flushPendingSaves();
closeSqlite();
console.log('TEXT_BILLING restart: balances preserved; repeated recovery and relay terminal do not charge twice');
