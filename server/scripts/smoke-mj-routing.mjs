import assert from 'node:assert/strict';
import fs from 'node:fs';
assert.ok(fs.existsSync(new URL('../.qiji-mj-routing-sandbox',import.meta.url)));
let wire;
globalThis.fetch=async(url,init)=>{wire={url:String(url),body:JSON.parse(init.body)};return new Response(JSON.stringify({code:200,data:{task_id:123456}}));};
const r=await import('../src/autoRouting.ts');
const models=await import('../src/store/models.ts');
const {buildCatalog}=await import('../src/catalog.ts');
const {imageUpstreamParams}=await import('../src/imageRouting.ts');
const {submitXiha888Image}=await import('../src/translators/xiha888.ts');
const line=r.routingConfig().lines.find(l=>l.familyId==='mid-journey'&&l.members.some(m=>m.enabled));
assert.ok(line);
const publicModel=r.lineModel(line);
assert.deepEqual(publicModel.params.find(f=>f.key==='quality').options,['0.25','0.5','1','2']);
assert.equal(publicModel.params.some(f=>f.key==='resolution'),false);
assert.equal(publicModel.params.find(f=>f.key==='aspectRatio').options.length,10);
assert.deepEqual(buildCatalog().models.find(m=>m.id===publicModel.id).params,publicModel.params);
const params=Object.fromEntries(publicModel.params.map(f=>[f.key,f.default]));
params.aspectRatio='4:5';params.quality='0.5';params.botType='NIJI_JOURNEY';params.stylize='0';params.chaos='100';params.style='raw';
const req={model:publicModel.id,purpose:'image.generate',promptOverride:'isolated MJ test',params};
assert.equal(r.prepareRoutingRequest(req),undefined);
const selected=r.selectRoute(req);
const model=models.getModelDef(selected.request.model);
const translated={...selected.request,params:imageUpstreamParams(model,selected.request.params)};
assert.equal((await submitXiha888Image(translated,{baseUrl:'https://mock.invalid',apiKey:'fake',upstreamModel:'mj_imagine'})).ok,true);
assert.deepEqual(wire.body.params,params);
assert.equal(wire.body.model,'mj_imagine');
assert.equal(wire.body.params.resolution,undefined);
assert.match(r.prepareRoutingRequest({...req,params:{...params,quality:'high'}}),/质量/);
assert.equal(wire.body.params.quality,'0.5');
console.log('PASS: live-data-copy catalog -> route validation -> selection -> upstream body; numeric quality, 10 ratios, native controls, no injected resolution, old high rejected before submit; zero live generation');
