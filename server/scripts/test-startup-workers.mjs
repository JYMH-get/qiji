import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {readRecoveryCandidates,recoveryWorkers} from '../src/startupRecovery.ts';
import {registerStartupReadiness} from '../src/startupReadiness.ts';
import Fastify from 'fastify';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'qiji-startup-workers-'));
const file=path.join(dir,'test.db');const db=new DatabaseSync(file);
db.exec('CREATE TABLE text_billing(log_id TEXT PRIMARY KEY,data TEXT NOT NULL)');
const insert=db.prepare('INSERT INTO text_billing VALUES(?,?)');
const ids=Array.from({length:2048},(_,i)=>'log-'+i);
db.exec('BEGIN');
for(const id of ids)insert.run(id,JSON.stringify({taskId:'task-'+id,result:{text:'x'.repeat(8192),usage:{inputTokens:1,outputTokens:1}}}));
insert.run('bad','invalid json');insert.run('pending',JSON.stringify({charged:{}}));db.exec('COMMIT');db.close();
const before=fs.readFileSync(file);
const timings=[];
for(const count of [1,2,4,8]){
 const seen=[];let beats=0;const timer=setInterval(()=>beats++,1);const start=performance.now();
 for await(const rows of readRecoveryCandidates(file,[...ids,'pending','missing'],count)) seen.push(...rows);
 clearInterval(timer);
 assert.deepEqual(seen.map(x=>x.logId).sort(),[...ids].sort());assert.ok(beats>0);
 assert.ok(seen.every(x=>!('result' in x)));
 timings.push({workers:recoveryWorkers(ids.length,count),ms:Math.round(performance.now()-start),heartbeats:beats});
}
assert.deepEqual(fs.readFileSync(file),before,'workers do not write ledger');
await assert.rejects(async()=>{for await(const _ of readRecoveryCandidates(file,['bad'])){/* drain */}},/JSON|Unexpected/);
assert.equal(recoveryWorkers(0),0);assert.equal(recoveryWorkers(1),1);assert.ok(recoveryWorkers(10000,99)<=8);
const app=Fastify(),state=registerStartupReadiness(app);let actions=0;
app.get('/health',async()=>({ok:true}));app.post('/v1/generate',async()=>{actions++;return {};});
assert.equal((await app.inject('/health')).statusCode,200);
assert.equal((await app.inject('/ready')).statusCode,503);
assert.equal((await app.inject({method:'POST',url:'/v1/generate'})).statusCode,503);assert.equal(actions,0);
state.ready();assert.equal((await app.inject('/ready')).statusCode,200);
assert.equal((await app.inject({method:'POST',url:'/v1/generate'})).statusCode,200);assert.equal(actions,1);
state.failed();assert.equal((await app.inject('/ready')).statusCode,503);
state.stopping();assert.equal((await app.inject({method:'POST',url:'/v1/generate'})).statusCode,503);
state.ready();assert.equal((await app.inject('/ready')).json().state,'stopping');
await app.close();
console.log(JSON.stringify({timings,readonly:true,malformedFailsClosed:true,readiness:true}));
