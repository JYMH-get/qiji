import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
if(!import.meta.url.includes('qiji-availability-'))throw Error('Sandbox only');
globalThis.fetch=async()=>{throw Error('No upstream allowed');};
const {channelAvailability,refreshChannelAvailability,stopChannelAvailabilityBackground}=await import('../src/channelAvailability.ts');
stopChannelAvailabilityBackground();
const row=channelAvailability().rows.find(r=>r.modelId==='av-gpt');
assert.equal(row.requests,3);
assert.equal(row.active,0);
assert.equal(row.successRate,2/3);
assert.equal(channelAvailability().rows.find(r=>r.modelId==='av-bulk').requests,10000);
assert.equal(channelAvailability().rows.filter(r=>r.capability==='other'&&r.modelId.startsWith('av-')).length,3);
assert.equal((await import('../src/store/families.ts')).getFamily('av-processing').capability,'video-enhance');
const {readChannelObservationState}=await import('../src/store/channelObservations.ts');
const fixture=JSON.parse(readFileSync('availability-history-restart.json','utf8'));
assert.deepEqual(readChannelObservationState('rate-history-v1'),fixture.persisted);
assert.equal(readChannelObservationState('rate-tracking-v1').active[fixture.lifeKey].since,fixture.lifeSince);
assert.equal(channelAvailability(fixture.lifeSince).rows.find(r=>r.modelId==='av-life').requests,0);
refreshChannelAvailability(fixture.sampleStart+14*60000,true);
assert.equal(readChannelObservationState('rate-history-v1').models[fixture.rowKey].pending.samples,5);
for(let i=15;i<20;i++)refreshChannelAvailability(fixture.sampleStart+i*60000,true);
const history=readChannelObservationState('rate-history-v1').models[fixture.rowKey];
assert.equal(history.history.length,2);
assert.equal(history.pending,undefined);
assert.deepEqual(history.history[0],fixture.persisted.models[fixture.rowKey].history[0]);
stopChannelAvailabilityBackground();(await import('../src/store/sqlite.ts')).closeSqlite();
console.log('AVAILABILITY restart passed: identities, counts, terminal states, rate history and partial group continuation');
