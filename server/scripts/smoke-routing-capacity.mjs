import assert from 'node:assert/strict';
import fs from 'node:fs';
assert.ok(fs.existsSync(new URL('../.qiji-routing-capacity-sandbox',import.meta.url)));
globalThis.fetch=async()=>{throw Error('No upstream calls allowed');};
const r=await import('../src/autoRouting.ts');
const original=r.routingConfig();
const draft=r.withDefaultRouting(r.withImageRouting(r.withSeedanceVariantRouting(original)));
assert.ok(draft.lines.length>100);
assert.ok(r.routingFamilyOptions(draft).some(f=>f.id==='mid-journey'));
const saved=r.saveRoutingConfig(draft);
assert.equal(saved.lines.length,draft.lines.length);
for(const line of original.lines)assert.deepEqual(saved.lines.find(l=>l.id===line.id),line);
assert.equal(saved.lines.filter(l=>l.familyId==='grok-4-6').length,4);
assert.equal(saved.lines.filter(l=>l.familyId==='mid-journey').length,4);
const bad=structuredClone(saved);bad.lines.at(-1).id='invalid id';
assert.throws(()=>r.saveRoutingConfig(bad),/线路身份/);
assert.deepEqual(r.routingConfig(),saved);
assert.throws(()=>r.saveRoutingConfig(draft),/配置已更新/);
console.log(JSON.stringify({original:original.lines.length,saved:saved.lines.length,existingLinesPreserved:true,mjVisible:true,invalidRejected:true,staleRejected:true}));
